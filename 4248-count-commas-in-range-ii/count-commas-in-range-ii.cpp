class Solution {
public:
    long long countCommas(long long n) {
        if(n <= 999999 && n>=1000){
            return n-1000+1;
        }

        if(n<=999999999 && n>=1000000){
            return n-1000+1 +  (n-1000000+1);
        }
        if(n<=999999999999 && n>=1000000000){
            return n-1000+1 +  (n-1000000+1) +  (n-1000000000+1);
        }
        if(n<=999999999999999 && n>=1000000000000){
            return n-1000+1 + (n-1000000+1) + (n-1000000000+1) + (n-1000000000000+1);
        }
        if(n==1000000000000000){
             return n-1000+1 +  (n-1000000+1) +  (n-1000000000+1) + (n-1000000000000+1) + 1;
        }
        return 0;
    }
};